"""Pydantic models for code review analysis, findings, reports, and fix suggestions."""
from typing import Dict, List, Literal, Optional
from pydantic import BaseModel, Field, field_validator


SeverityLevel = Literal["critical", "high", "medium", "low", "info"]
FindingCategory = Literal["correctness", "security", "performance", "maintainability", "style"]
ConfidenceLevel = Literal["low", "medium", "high"]
FindingSource = Literal["ai", "static", "ai_and_static", "gemini_ai"]

_CATEGORY_MAP = {
    "bug": "correctness",
    "defect": "correctness",
    "error": "correctness",
    "logic": "correctness",
    "correct": "correctness",
    "vuln": "security",
    "vulnerability": "security",
    "sec": "security",
    "perf": "performance",
    "speed": "performance",
    "clean": "maintainability",
    "refactor": "maintainability",
    "quality": "maintainability",
    "lint": "style",
    "formatting": "style",
}

_SEVERITY_MAP = {
    "blocker": "critical",
    "fatal": "critical",
    "severe": "critical",
    "major": "high",
    "warn": "medium",
    "warning": "medium",
    "minor": "low",
    "note": "info",
    "suggestion": "info",
}


class ReviewFinding(BaseModel):
    """Structured code review finding generated by Gemini AI or static analyzers."""
    id: str = Field(..., description="Unique finding identifier (e.g., finding_001)")
    title: str = Field(..., description="Concise summary of the identified issue")
    category: FindingCategory = Field(..., description="Finding category")
    severity: SeverityLevel = Field(..., description="Severity level")
    file: str = Field(..., description="Filename being analyzed")
    start_line: int = Field(..., ge=1, description="1-based starting line number in source code")
    end_line: int = Field(..., ge=1, description="1-based ending line number in source code")
    evidence: str = Field(default="", description="Snippet or line of source code exhibiting the issue")
    explanation: str = Field(..., description="Detailed explanation of the issue and why it poses a problem")
    recommendation: str = Field(..., description="Actionable recommendation or code change to resolve the issue")
    confidence: ConfidenceLevel = Field(default="medium", description="Qualitative confidence assessment")
    source: FindingSource = Field(default="ai", description="Origin of finding: ai, static, or ai_and_static")
    analyzer_name: Optional[str] = Field(default=None, description="Name of static analyzer or engine (e.g., ruff, bandit, eslint)")
    rule_id: Optional[str] = Field(default=None, description="Linter or security rule ID (e.g., F841, B608)")
    fix_available: Optional[bool] = Field(default=True, description="Whether an automated fix can be proposed")
    merged_sources: Optional[List[str]] = Field(default=None, description="Detailed sources if merged during deduplication")

    @field_validator("category", mode="before")
    @classmethod
    def normalize_category_input(cls, v: str) -> str:
        val = (v or "").strip().lower()
        if val in {"correctness", "security", "performance", "maintainability", "style"}:
            return val
        for syn, target in _CATEGORY_MAP.items():
            if syn in val:
                return target
        return "maintainability"

    @field_validator("severity", mode="before")
    @classmethod
    def normalize_severity_input(cls, v: str) -> str:
        val = (v or "").strip().lower()
        if val in {"critical", "high", "medium", "low", "info"}:
            return val
        for syn, target in _SEVERITY_MAP.items():
            if syn in val:
                return target
        return "medium"

    @field_validator("source", mode="before")
    @classmethod
    def normalize_source_input(cls, v: str) -> str:
        val = (v or "").strip().lower()
        if val in {"ai", "static", "ai_and_static", "gemini_ai"}:
            return val
        if "static" in val:
            return "static"
        return "ai"


class ReviewSeverityBreakdown(BaseModel):
    """Aggregated count of findings grouped by severity."""
    critical: int = Field(default=0, ge=0)
    high: int = Field(default=0, ge=0)
    medium: int = Field(default=0, ge=0)
    low: int = Field(default=0, ge=0)
    info: int = Field(default=0, ge=0)


class ReviewAnalyzeRequest(BaseModel):
    """Request payload for analyzing source code."""
    code: str = Field(..., min_length=1, description="Source code content to analyze")
    language: str = Field(..., min_length=1, description="Canonical language identifier")
    filename: Optional[str] = Field(default=None, description="Optional filename")
    mode: Optional[Literal["combined", "ai_only", "static_only"]] = Field(
        default="combined",
        description="Analysis execution mode: combined (default), ai_only, or static_only"
    )

    @field_validator("code")
    @classmethod
    def validate_code_not_blank(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Source code cannot be empty.")
        return v

    @field_validator("language")
    @classmethod
    def validate_language_not_blank(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Programming language must be specified.")
        return v.strip().lower()


class ReviewReport(BaseModel):
    """Complete structured code review report combining AI and static analysis."""
    id: str = Field(..., description="Unique review report identifier")
    file: str = Field(..., description="Analyzed filename")
    language: str = Field(..., description="Canonical language identifier")
    model: str = Field(..., description="Gemini model or analyzer pipeline identifier")
    summary: str = Field(..., description="Executive summary of review results")
    total_findings: int = Field(..., ge=0, description="Total number of validated findings")
    severity_breakdown: ReviewSeverityBreakdown = Field(..., description="Count of findings per severity")
    findings: List[ReviewFinding] = Field(default_factory=list, description="List of validated findings")
    positive_observations: List[str] = Field(default_factory=list, description="Strengths and well-written aspects")
    general_recommendations: List[str] = Field(default_factory=list, description="Broad architecture/hygiene tips")
    analyzed_at: str = Field(..., description="ISO 8601 timestamp of analysis")
    duration_ms: Optional[int] = Field(default=None, description="Time taken to process in milliseconds")
    status: Literal["completed", "warning", "failed"] = Field(default="completed")
    
    # Day 4 additions for static analysis & source breakdown
    ai_findings_count: int = Field(default=0, ge=0, description="Count of findings detected by AI")
    static_findings_count: int = Field(default=0, ge=0, description="Count of findings detected by static analyzers")
    combined_findings_count: int = Field(default=0, ge=0, description="Count of findings verified by both AI and static analysis")
    analyzers_executed: List[str] = Field(default_factory=list, description="List of analyzers successfully executed")
    analyzer_errors: Dict[str, str] = Field(default_factory=dict, description="Analyzer-specific non-fatal errors or status")


# --- Day 4 Fix Suggestion & Patch Models ---

class SuggestedFix(BaseModel):
    """Structured code patch proposed for a specific finding."""
    finding_id: str = Field(..., description="Target finding ID")
    file: str = Field(..., description="Target file name")
    start_line: int = Field(..., ge=1, description="1-based starting line of original code to replace")
    end_line: int = Field(..., ge=1, description="1-based ending line of original code to replace")
    original_code: str = Field(..., description="Exact original code snippet being replaced")
    replacement_code: str = Field(..., description="Proposed replacement code snippet")
    explanation: str = Field(..., description="Explanation of why this fix resolves the issue")
    diff: Optional[str] = Field(default=None, description="Unified diff preview")
    applied: bool = Field(default=False, description="Whether fix has been applied to source")


class SuggestFixRequest(BaseModel):
    """Request to generate a contextual fix suggestion for a finding."""
    finding_id: str = Field(..., description="Finding identifier")
    code: str = Field(..., min_length=1, description="Current full source code")
    language: str = Field(..., min_length=1, description="Language identifier")
    filename: Optional[str] = Field(default=None, description="Filename")
    finding: Optional[ReviewFinding] = Field(default=None, description="Finding details if not stored on server")


class ApplyFixRequest(BaseModel):
    """Request to validate and apply a proposed fix to the current source code."""
    code: str = Field(..., min_length=1, description="Current source code in editor")
    fix: SuggestedFix = Field(..., description="Structured fix patch to apply")
    filename: Optional[str] = Field(default=None, description="Filename being edited")


class ApplyFixResponse(BaseModel):
    """Response returned upon applying or rejecting a patch."""
    success: bool = Field(..., description="Whether patch was successfully applied")
    updated_code: str = Field(..., description="New source code with patch applied")
    message: str = Field(..., description="User-facing status message")
    lines_affected: int = Field(default=0, description="Number of lines replaced or modified")
    undo_available: bool = Field(default=True, description="Indicates undo is supported")


class RejectFixRequest(BaseModel):
    """Request to record user rejection of a proposed fix."""
    finding_id: str = Field(..., description="Target finding identifier")
    reason: Optional[str] = Field(default=None, description="Optional developer rationale for rejection")
